/* Custom maps from tag_map_editor.html override the built-ins (same browser).
   Editor saves to 'tag_arena_custom_maps_v1'; invalid saves are ignored safely. */
function syncCustomMaps(){
  try{
    const raw=localStorage.getItem('tag_arena_custom_maps_v1');
    if(!raw)return;
    const a=JSON.parse(raw);
    if(!Array.isArray(a)||!a.length)return;
    const ok=a.every(m=>m&&typeof m.name==='string'&&['solids','speeds','drops','boosts'].every(k=>
      Array.isArray(m[k])&&m[k].every(p=>Array.isArray(p)&&p.length>=4&&p.slice(0,4).every(Number.isFinite))));
    if(ok&&a.length<=40)MAPS.splice(0,MAPS.length,...a);
  }catch(e){/* keep built-in maps */}
}
function buildLevel(){
  const M=MAPS[settings.map%MAPS.length];
  SOLIDS=[
    {x:0,y:0,w:W,h:WALL,t:'solid',wall:1},{x:0,y:H-WALL,w:W,h:WALL,t:'solid',wall:1},
    {x:0,y:0,w:WALL,h:H,t:'solid',wall:1},{x:W-WALL,y:0,w:WALL,h:H,t:'solid',wall:1}
  ];
  /* All horizontal platforms are normalized to player height (46px); tops stay put so jump gaps never change */
  const P46=a=>({x:a[0],y:a[1],w:a[2],h:(a[3]<=32?46:a[3]),dy:a[4]||0});
  for(const a of M.solids){const p=P46(a);p.t='solid';SOLIDS.push(p);}
  for(const a of M.speeds){const p=P46(a);p.t='speed';SOLIDS.push(p);}
  for(const a of M.drops){const p=P46(a);p.t='drop';SOLIDS.push(p);}
  for(const a of M.boosts){const p=P46(a);p.t='boost';SOLIDS.push(p);}
}

